import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
const [base='http://127.0.0.1:4173',out='test-results/tutorial']=process.argv.slice(2);
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch();
try {
 const context=await browser.newContext({serviceWorkers:'block',reducedMotion:'reduce',viewport:{width:1440,height:1000}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${base}/?lang=en&theme=light#/world`);
 await page.locator('.tutorial-welcome').waitFor();assert.equal(await page.getByRole('dialog').count(),0);
 await page.getByRole('button',{name:'Show me around',exact:true}).click();
 const coach=page.getByRole('dialog');const next=coach.getByRole('button',{name:'Continue',exact:false});
 await coach.waitFor();assert.equal(await next.isDisabled(),true);
 await coach.getByRole('button',{name:'Use the keyboard instead'}).click();
 await page.locator('#world-country').selectOption('bra');await next.click();
 assert.match(await page.locator('#tutorial-heading').innerText(),/Read the sightings/);await next.click();
 await page.locator('#world-sensor').selectOption('modis');await next.click();
 await page.locator('#world-day').fill('1');await page.locator('#world-day').focus();await page.keyboard.press('ArrowRight');await page.waitForURL(/day=2/);
 assert.equal(await page.evaluate(()=>document.activeElement?.id),'world-day');await next.click();
 await page.getByRole('button',{name:'Watch this country',exact:true}).click();await next.click();
 await page.locator('.experiment-controls.tutorial-target').waitFor();await next.click();
 assert.equal(await next.isDisabled(),true);await page.getByRole('button',{name:'Reveal actual VIIRS',exact:true}).click();await next.click();
 await page.locator('.global-evidence.tutorial-target').waitFor();
 assert.deepEqual((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations.map(v=>v.id),[]);
 await page.screenshot({path:path.join(out,'tutorial-desktop.png')});
 await coach.getByRole('button',{name:'Explore on my own'}).click();await page.waitForURL(/#\/world$/);
 assert.equal(await page.locator('.tutorial-target').count(),0);assert.equal(await page.evaluate(()=>localStorage.getItem('ap-tutorial-v1')),'done');
 await page.reload();assert.equal(await page.locator('.tutorial-welcome').count(),0);
 const original='/home?r=d_rangamati&y=2024&w=17&s=harm%2Cviirs&kilns=1';await page.goto(`${base}/?lang=en&theme=dark#${original}`);
 await page.getByRole('button',{name:'Show me around',exact:true}).click();await coach.waitFor();await page.keyboard.press('Escape');await page.waitForURL(url=>url.hash===`#${original}`);
 const mobile=await context.newPage();await mobile.setViewportSize({width:390,height:844});await mobile.goto(`${base}/?lang=bn&theme=dark#/world`);
 await mobile.locator('.demo-launch>.btn').click();await mobile.getByRole('dialog').waitFor();await mobile.locator('.tutorial-target').waitFor();
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual((await new AxeBuilder({page:mobile}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations.map(v=>v.id),[]);
 await mobile.screenshot({path:path.join(out,'tutorial-phone-bn.png')});await mobile.keyboard.press('Escape');
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(out,'tutorial.json'),JSON.stringify({steps:8,realActions:true,firstVisitOffer:true,completionPersists:true,escapeRestoresFilters:true,mobileBangla:true,axeViolations:0,errors},null,2));
 console.log('PASS: eight action-led tutorial steps, first visit/replay, skip/escape, saved completion, original filters, mobile Bangla and accessibility');
} finally {await browser.close();}
