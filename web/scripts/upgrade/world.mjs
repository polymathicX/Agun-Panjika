import {chromium} from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
const [base='http://127.0.0.1:4173',out='test-results/world-release']=process.argv.slice(2);
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch();
try {
 const context=await browser.newContext({viewport:{width:1440,height:1080},reducedMotion:'reduce'});
 const page=await context.newPage();
 const choose=async id=>{const d=page.locator('.world-controls details').first();if(await d.getAttribute('open')===null)await d.locator('summary').click();await page.locator('#world-country').selectOption(id);await d.evaluate(e=>e.open=false);};const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${base}/?lang=en&theme=light`);
 await page.locator('#world-country').waitFor({state:'attached'});
 assert.ok(await page.locator('#world-country option').count()>200);
 await page.locator('.earth-realistic[data-ready=true]').waitFor();
 await page.locator('.world-globe .earth-scene').click({position:{x:await page.locator('.world-globe .earth-scene').evaluate(e=>e.clientWidth/2),y:await page.locator('.world-globe .earth-scene').evaluate(e=>e.clientHeight/2)}});
 await page.waitForURL(/country=sdn/);
 await choose('bra');await page.waitForURL(/country=bra/);
 assert.equal(await page.locator('.world-highlight h2').innerText(),'Brazil');
 await page.getByRole('button',{name:'Watch this country',exact:true}).click();
 await page.reload();await page.locator('.world-watchlist').waitFor();
 assert.match(await page.locator('.world-watchlist').innerText(),/Brazil/);
 await choose('jpn');await page.waitForURL(/country=jpn/);
 const countryDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Download country evidence',exact:true}).click();const countryFile=await countryDownload;await countryFile.saveAs(path.join(out,'country-evidence.json'));const countryReport=JSON.parse(await fs.readFile(path.join(out,'country-evidence.json'),'utf8'));assert.equal(countryReport.country,'Japan');assert.ok(countryReport.source_sha256);
 await page.getByLabel('Satellite',{exact:true}).selectOption('noaa21');await page.waitForURL(/sensor=noaa21/);
 await page.locator('#world-day').fill('2');await page.waitForURL(/day=2/);
 await page.getByRole('button',{name:'Play timeline',exact:true}).click();await page.waitForURL(/day=3/);await page.getByRole('button',{name:'Pause timeline',exact:true}).click();
 await choose('');await page.getByLabel('Satellite',{exact:true}).selectOption('noaa20');await page.locator('#world-day').fill('-1');
 await page.locator('.earth-realistic[data-ready=true]').waitFor();
 await page.screenshot({path:path.join(out,'world-desktop.png'),fullPage:true});
 assert.deepEqual((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})),[]);
 await page.evaluate(()=>navigator.serviceWorker.ready);
 const manifest=await page.request.get(`${base}/manifest.webmanifest`);const app=await manifest.json();
 assert.equal(app.display,'standalone');assert.equal(app.icons.length,2);
 const session=await context.newCDPSession(page);const install=await session.send('Page.getInstallabilityErrors');
 assert.deepEqual(install.installabilityErrors,[]);
 await page.setViewportSize({width:390,height:844});await choose('bgd');
 await page.waitForURL(/country=bgd/);await page.screenshot({path:path.join(out,'world-mobile.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.goto(`${base}/?lang=bn&theme=dark#/world?country=can`);await page.locator('#world-country').waitFor({state:'attached'});
 assert.deepEqual((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations.map(v=>v.id),[]);
 await session.detach();
 const offlineContext=await browser.newContext();const offline=await offlineContext.newPage();
 await offline.goto(`${base}/?lang=en#/world`);await offline.evaluate(()=>navigator.serviceWorker.ready);await offline.reload();await offline.locator('.world-highlight').waitFor();
 await offlineContext.setOffline(true);await offline.goto(`${base}/?source=pwa#/world`);await offline.locator('.offline-status').waitFor();await offline.locator('.world-highlight').waitFor();
 // A never-visited lazy route must work from precache, including Vary: Origin module responses.
 await offline.goto(`${base}/?lang=en#/global?area=nepal`);await offline.locator('#evidence-h').waitFor();
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(out,'world.json'),JSON.stringify({countries:242,globePicking:true,keyboardSelection:true,sensors:3,timeline:true,watchlist:true,installability:install,offlineShellAndCases:true,errors},null,2));
 console.log('PASS: world globe country picking, 242 country access, sensors, timeline, watchlist, mobile accessibility, PWA installability and offline reference cases');
} finally {await browser.close();}
